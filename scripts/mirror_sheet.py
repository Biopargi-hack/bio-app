#!/usr/bin/env python3
"""Mirror the connected Tap to Prove Google Sheet into data/sheet."""

import csv
import json
import os
import re
import shutil
import subprocess
import unicodedata
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "data" / "sheet"
ID_FILE = Path.home() / "AI-drop" / "taptoprove_sheets" / "google_sheet_id.txt"
WORKBOOK = Path.home() / "AI-drop" / "taptoprove_sheets" / "taptoprove_ledger.xlsx"


def sheet_id():
    value = os.environ.get("TAPTOPROVE_SHEET_ID", "").strip()
    if value:
        return value
    if ID_FILE.exists():
        return ID_FILE.read_text(encoding="utf-8").strip()
    raise SystemExit("Set TAPTOPROVE_SHEET_ID or create " + str(ID_FILE))


def gws(args):
    result = subprocess.run(
        ["gws", "sheets"] + args,
        check=True,
        capture_output=True,
        text=True,
    )
    return json.loads(result.stdout)


def slug(title):
    text = unicodedata.normalize("NFKD", title).encode("ascii", "ignore").decode("ascii")
    return "".join(ch.lower() if ch.isalnum() else "_" for ch in text).strip("_")


def excel_value(value):
    text = "" if value is None else str(value)
    if re.fullmatch(r"-?\d+\.\d+", text):
        return text.replace(".", ",")
    return text


def main():
    sid = sheet_id()
    info = gws(
        [
            "spreadsheets",
            "get",
            "--params",
            json.dumps({"spreadsheetId": sid}),
            "--format",
            "json",
        ]
    )
    title = info.get("properties", {}).get("title", "Connected sheet")
    OUT.mkdir(parents=True, exist_ok=True)

    tabs = []
    for item in info.get("sheets", []):
        name = item.get("properties", {}).get("title")
        if not name:
            continue
        escaped = name.replace("'", "''")
        values = gws(
            [
                "spreadsheets",
                "values",
                "get",
                "--params",
                json.dumps(
                    {
                        "spreadsheetId": sid,
                        "range": f"'{escaped}'!A1:ZZ10000",
                    }
                ),
                "--format",
                "json",
            ]
        )
        rows = values.get("values", [])
        width = max((len(row) for row in rows), default=1)
        filename = slug(name) + ".csv"
        with (OUT / filename).open("w", newline="", encoding="utf-8-sig") as handle:
            writer = csv.writer(handle, delimiter=";", lineterminator="\r\n")
            for row in rows:
                writer.writerow([excel_value(value) for value in row] + [""] * (width - len(row)))
        tabs.append(
            {
                "title": name,
                "file": filename,
                "rows": max(len(rows) - 1, 0),
                "columns": width,
            }
        )
        print(filename + ": " + str(len(rows)) + " rows")

    workbook = None
    source = Path(os.environ.get("TAPTOPROVE_WORKBOOK", str(WORKBOOK)))
    if source.exists():
        shutil.copy2(source, OUT / "taptoprove_ledger.xlsx")
        workbook = "taptoprove_ledger.xlsx"
        print("workbook: " + workbook)

    manifest = {
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "sheet_title": title,
        "tabs": tabs,
        "workbook": workbook,
    }
    (OUT / "manifest.json").write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    (OUT / "README.md").write_text(
        "# Connected sheet mirror\n\n"
        "This folder is generated by `python3 scripts/mirror_sheet.py`.\n\n"
        "CSV files are the readable GitHub copy of the connected Tap to Prove Google Sheet. "
        "They use a UTF-8 BOM and semicolon separators so they open in Estonian Excel. "
        "The workbook snapshot is copied when the local sync workbook exists.\n\n"
        "The sheet ID is read from `TAPTOPROVE_SHEET_ID` or the local sync folder. "
        "It is not stored in this repo.\n\n"
        "Do not edit these files by hand. Refresh them after the sheet changes and commit the result.\n",
        encoding="utf-8",
    )
    print("wrote " + str(OUT))


if __name__ == "__main__":
    main()
